--changeset robert_neat:loan_application-001
CREATE TABLE loan_application (
    id VARCHAR(10) PRIMARY KEY,
    customer_id VARCHAR(20) NOT NULL REFERENCES customer (id),
    segment VARCHAR(10) NOT NULL CHECK (segment IN ('retail', 'business')),
    product VARCHAR(20) NOT NULL
        CHECK (product IN ('cash', 'mortgage', 'overdraft', 'investment', 'creditLine')),
    stage VARCHAR(20) NOT NULL
        CHECK (stage IN ('application', 'scoring', 'affordability', 'decision', 'contract',
                         'disbursement', 'schedule', 'collections')),
    requested_amount NUMERIC(19, 2) NOT NULL,
    approved_amount NUMERIC(19, 2),
    score_result INTEGER,
    dsti NUMERIC(4, 3),
    bureau_inquiry_id VARCHAR(36),
    interest_rate NUMERIC(5, 4) NOT NULL,
    term_months INTEGER NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

--changeset robert_neat:loan_stage_transition-001
CREATE TABLE loan_stage_transition (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_application_id VARCHAR(10) NOT NULL REFERENCES loan_application (id),
    from_stage VARCHAR(20) NOT NULL
        CHECK (from_stage IN ('application', 'scoring', 'affordability', 'decision', 'contract',
                              'disbursement', 'schedule', 'collections')),
    to_stage VARCHAR(20) NOT NULL
        CHECK (to_stage IN ('application', 'scoring', 'affordability', 'decision', 'contract',
                            'disbursement', 'schedule', 'collections')),
    approval_id VARCHAR(36),
    transitioned_at TIMESTAMP WITH TIME ZONE NOT NULL,
    transitioned_by VARCHAR(10) NOT NULL REFERENCES employee (id)
);

--changeset robert_neat:installment-001
CREATE TABLE installment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_application_id VARCHAR(10) NOT NULL REFERENCES loan_application (id),
    installment_no INTEGER NOT NULL,
    due_date DATE NOT NULL,
    principal NUMERIC(19, 2) NOT NULL,
    interest NUMERIC(19, 2) NOT NULL,
    status VARCHAR(10) NOT NULL CHECK (status IN ('paid', 'upcoming', 'overdue'))
);
