--changeset robert_neat:collections_case-001
CREATE TABLE collections_case (
    id VARCHAR(10) PRIMARY KEY,
    loan_application_id VARCHAR(10) NOT NULL REFERENCES loan_application (id),
    days_past_due INTEGER NOT NULL,
    outstanding_amount NUMERIC(19, 2) NOT NULL,
    stage VARCHAR(20) NOT NULL
        CHECK (stage IN ('monitoring', 'reminder', 'settlement', 'restructuring', 'external', 'legal'))
);

--changeset robert_neat:collections_action-001
CREATE TABLE collections_action (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collections_case_id VARCHAR(10) NOT NULL REFERENCES collections_case (id),
    action_type VARCHAR(20) NOT NULL
        CHECK (action_type IN ('REMINDER_SENT', 'SETTLEMENT_PROPOSED', 'EXTERNAL_TRANSFER')),
    performed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    performed_by VARCHAR(10) NOT NULL REFERENCES employee (id),
    governance_audit_event_id VARCHAR(36)
);
