CREATE TABLE regulatory_report (
    id VARCHAR(15) PRIMARY KEY,
    recipient VARCHAR(10) NOT NULL CHECK (recipient IN ('KNF', 'NBP', 'BFG', 'FATCA/CRS')),
    name VARCHAR(200) NOT NULL,
    period VARCHAR(20) NOT NULL,
    due_date DATE NOT NULL,
    status VARCHAR(15) NOT NULL CHECK (status IN ('draft', 'submitted', 'accepted'))
);

--changeset robert_neat:report_submission-001
CREATE TABLE report_submission (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    regulatory_report_id VARCHAR(15) NOT NULL REFERENCES regulatory_report (id),
    gateway_submission_id VARCHAR(36) NOT NULL UNIQUE,
    gateway_status VARCHAR(15) NOT NULL CHECK (gateway_status IN ('PENDING', 'ACCEPTED', 'REJECTED')),
    validation_errors VARCHAR(1000),
    submitted_at TIMESTAMP WITH TIME ZONE NOT NULL,
    resolved_at TIMESTAMP WITH TIME ZONE
);
